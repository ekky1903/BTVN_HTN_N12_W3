// Ham truyen tung mau so len PC qua UART ngat nhau boi \r\n
static void Send_ADC_Data_UART(uint16_t *pData, uint16_t length)
{
  for (uint16_t i = 0; i < length; i++)
  {
    int len = snprintf(tx_buffer, sizeof(tx_buffer), "%u\r\n", pData[i]);
    if (len > 0)
    {
      HAL_UART_Transmit(&huart1, (uint8_t*)tx_buffer, (uint16_t)len, HAL_MAX_DELAY);
    }
  }
}
